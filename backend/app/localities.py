BY_SLUG = {loc["slug"]: loc for loc in BANGALORE}


def find_locality(query: str):
    q = (query or "").strip().lower()
    if not q:
        return None
    if q in BY_SLUG:
        return BY_SLUG[q]
    for loc in BANGALORE:
        if loc["pincode"] == q or loc["name"].lower() == q:
            return loc
    for loc in BANGALORE:
        if q in loc["name"].lower() or loc["name"].lower() in q:
            return loc
    tokens = [t for t in q.replace(",", " ").split() if len(t) > 2]
    best, best_hits = None, 0
    for loc in BANGALORE:
        name = loc["name"].lower()
        hits = sum(1 for t in tokens if t in name)
        if hits > best_hits:
            best, best_hits = loc, hits
    return best


def search_localities(query: str, limit: int = 12):
    q = (query or "").strip().lower()
    if not q:
        return BANGALORE[:limit]
    scored = []
    for loc in BANGALORE:
        name = loc["name"].lower()
        if name.startswith(q):
            scored.append((0, loc))
        elif q in name or q in loc["pincode"] or q in loc["zone"].lower():
            scored.append((1, loc))
        elif q in loc["blurb"].lower():
            scored.append((2, loc))
    scored.sort(key=lambda x: x[0])
    return [loc for _, loc in scored[:limit]]
