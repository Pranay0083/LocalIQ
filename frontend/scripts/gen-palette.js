/* Generates src/palette.css — a reversible colour ramp so the whole app flips light/dark. */
const fs = require("fs");
const path = require("path");

const T = {
  indigo: ["#EEF2FF","#E0E7FF","#C7D2FE","#A5B4FC","#818CF8","#6366F1","#4F46E5","#4338CA","#3730A3","#312E81","#1E1B4B"],
  violet: ["#F5F3FF","#EDE9FE","#DDD6FE","#C4B5FD","#A78BFA","#8B5CF6","#7C3AED","#6D28D9","#5B21B6","#4C1D95","#2E1065"],
  blue:   ["#EFF6FF","#DBEAFE","#BFDBFE","#93C5FD","#60A5FA","#3B82F6","#2563EB","#1D4ED8","#1E40AF","#1E3A8A","#172554"],
  cyan:   ["#ECFEFF","#CFFAFE","#A5F3FC","#67E8F9","#22D3EE","#06B6D4","#0891B2","#0E7490","#155E75","#164E63","#083344"],
  teal:   ["#F0FDFA","#CCFBF1","#99F6E4","#5EEAD4","#2DD4BF","#14B8A6","#0D9488","#0F766E","#115E59","#134E4A","#042F2E"],
  emerald:["#ECFDF5","#D1FAE5","#A7F3D0","#6EE7B7","#34D399","#10B981","#059669","#047857","#065F46","#064E3B","#022C22"],
  amber:  ["#FFFBEB","#FEF3C7","#FDE68A","#FCD34D","#FBBF24","#F59E0B","#D97706","#B45309","#92400E","#78350F","#451A03"],
  red:    ["#FEF2F2","#FEE2E2","#FECACA","#FCA5A5","#F87171","#EF4444","#DC2626","#B91C1C","#991B1B","#7F1D1D","#450A0A"],
  pink:   ["#FDF2F8","#FCE7F3","#FBCFE8","#F9A8D4","#F472B6","#EC4899","#DB2777","#BE185D","#9D174D","#831843","#500724"],
  slate:  ["#F8FAFC","#F1F5F9","#E2E8F0","#CBD5E1","#94A3B8","#64748B","#475569","#334155","#1E293B","#0F172A","#020617"],
};

const ZINC_DARK = ["#FAFAFA","#F4F4F5","#E4E4E7","#D4D4D8","#A1A1AA","#71717A","#52525B","#3F3F46","#27272A","#18181B","#09090B"];
// Light mode inverts the neutral ramp: 50 = strongest ink, 950 = paper.
const ZINC_LIGHT = ["#0B1120","#111827","#1F2937","#334155","#475569","#5B6B7F","#6B7A90","#94A3B8","#D3DBE5","#E4E9F0","#FFFFFF"];

const SHADES = [50,100,200,300,400,500,600,700,800,900,950];
// index into the true tailwind ramp for each shade when rendering on a light surface
const LIGHT_MAP = [0, 1, 7, 7, 7, 6, 6, 4, 4, 4, 5];

const rgb = (hex) => {
  const h = hex.replace("#", "");
  return `${parseInt(h.slice(0, 2), 16)} ${parseInt(h.slice(2, 4), 16)} ${parseInt(h.slice(4, 6), 16)}`;
};

const block = (mode) => {
  const lines = [];
  SHADES.forEach((s, i) => {
    lines.push(`  --c-zinc-${s}: ${rgb(mode === "light" ? ZINC_LIGHT[i] : ZINC_DARK[i])};`);
  });
  Object.entries(T).forEach(([name, ramp]) => {
    SHADES.forEach((s, i) => {
      const hex = mode === "light" ? ramp[LIGHT_MAP[i]] : ramp[i];
      lines.push(`  --c-${name}-${s}: ${rgb(hex)};`);
    });
  });
  return lines.join("\n");
};

const css = `/* AUTO-GENERATED by scripts/gen-palette.js — do not edit by hand. */
:root {
${block("light")}
}

.dark {
${block("dark")}
}
`;

fs.writeFileSync(path.join(__dirname, "..", "src", "palette.css"), css);
console.log("palette.css written");
