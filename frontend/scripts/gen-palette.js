/* Generates src/palette.css: every Tailwind colour ramp the app uses, resolved per theme.

   The chrome is achromatic. Neutrals carry text and surfaces; the old brand ramps (indigo, violet,
   teal, cyan, pink, slate) resolve to ink so no hue reaches the chrome; status ramps (emerald, amber,
   red) keep their meaning; blue is the one data hue, kept for the score made for the reader. */
const fs = require("fs");
const path = require("path");

const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];

// Light: 50 is the strongest ink and 950 is paper, so classes read as "50 = text, 950 = surface".
const NEUTRAL_LIGHT = ["#0A0A0A", "#141414", "#262626", "#333333", "#4A4A4A", "#5C5C5C", "#6B6B6B", "#707070", "#D4D4D4", "#E6E6E6", "#FFFFFF"];
const NEUTRAL_DARK = ["#FAFAFA", "#F4F4F5", "#E4E4E7", "#D4D4D8", "#B4B4B4", "#A3A3A3", "#9A9A9A", "#8F8F8F", "#2E2E2E", "#1F1F1F", "#111111"];

// Former brand ramps: tints for areas, ink for marks and fills.
const INK_LIGHT = ["#F4F4F4", "#EEEEEE", "#141414", "#141414", "#141414", "#141414", "#141414", "#3D3D3D", "#3D3D3D", "#3D3D3D", "#141414"];
const INK_DARK = ["#1F1F1F", "#262626", "#F5F5F5", "#F5F5F5", "#F5F5F5", "#E5E5E5", "#E5E5E5", "#B4B4B4", "#B4B4B4", "#B4B4B4", "#F5F5F5"];

const status = (tint1, tint2, ink, dark1, dark2, darkInk) => ({
  light: [tint1, tint2, ink, ink, ink, ink, ink, ink, ink, ink, ink],
  dark: [dark1, dark2, darkInk, darkInk, darkInk, darkInk, darkInk, darkInk, darkInk, darkInk, darkInk],
});

const RAMPS = {
  zinc: { light: NEUTRAL_LIGHT, dark: NEUTRAL_DARK },
  slate: { light: NEUTRAL_LIGHT, dark: NEUTRAL_DARK },
  indigo: { light: INK_LIGHT, dark: INK_DARK },
  violet: { light: INK_LIGHT, dark: INK_DARK },
  teal: { light: INK_LIGHT, dark: INK_DARK },
  cyan: { light: INK_LIGHT, dark: INK_DARK },
  pink: { light: INK_LIGHT, dark: INK_DARK },
  blue: status("#EEF3FB", "#DCE7F7", "#1D5FBF", "#13233A", "#182C49", "#6EA2EC"),
  emerald: status("#EEF7EF", "#DCFAE5", "#2E7D32", "#172A1D", "#1C3524", "#3FC07A"),
  amber: status("#FFFBEB", "#FEF3C7", "#92400E", "#2A2113", "#35291A", "#E0A44A"),
  red: status("#FFF4F2", "#FFEDEA", "#C4242A", "#2C1A20", "#3A1F27", "#E5566F"),
};

const rgb = (hex) => {
  const h = hex.replace("#", "");
  return `${parseInt(h.slice(0, 2), 16)} ${parseInt(h.slice(2, 4), 16)} ${parseInt(h.slice(4, 6), 16)}`;
};

const block = (mode) =>
  Object.entries(RAMPS)
    .flatMap(([name, ramp]) => SHADES.map((s, i) => `  --c-${name}-${s}: ${rgb(ramp[mode][i])};`))
    .join("\n");

const css = `/* AUTO-GENERATED by scripts/gen-palette.js — do not edit by hand. */
:root {
${block("light")}
}

.dark {
${block("dark")}
}
`;

fs.writeFileSync(path.join(__dirname, "..", "src", "palette.css"), css);
console.log("palette.css written");
